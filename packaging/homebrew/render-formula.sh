#!/usr/bin/env bash
# Prints the Homebrew formula (Formula/pen.rb in mmonteleone/homebrew-tap) for a
# release, from the SHA256SUMS published with it. The release workflow runs it.
#
#   packaging/homebrew/render-formula.sh VERSION SHA256SUMS > pen.rb
set -euo pipefail

version=${1:?usage: render-formula.sh VERSION SHA256SUMS}
sums=${2:?usage: render-formula.sh VERSION SHA256SUMS}
base=https://github.com/mmonteleone/pen/releases/download/v$version

sha() {
  local name=pen-$version-$1.tar.gz hash
  hash=$(awk -v n="$name" '$2 == n || $2 == "*" n { print $1 }' "$sums")
  if ! [[ $hash =~ ^[0-9a-f]{64}$ ]]; then
    echo "render-formula.sh: no SHA-256 for $name in $sums" >&2
    exit 1
  fi
  echo "$hash"
}

osx_arm64=$(sha osx-arm64)
osx_x64=$(sha osx-x64)
linux_arm64=$(sha linux-arm64)
linux_x64=$(sha linux-x64)

cat <<EOF
# Generated by packaging/homebrew/render-formula.sh in mmonteleone/pen; edits here are overwritten by the next release.
class Pen < Formula
  desc "Run AI coding agents in Docker with an egress allowlist"
  homepage "https://github.com/mmonteleone/pen"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/pen-$version-osx-arm64.tar.gz"
      sha256 "$osx_arm64"
    end
    on_intel do
      url "$base/pen-$version-osx-x64.tar.gz"
      sha256 "$osx_x64"
    end
  end

  on_linux do
    on_arm do
      url "$base/pen-$version-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/pen-$version-linux-x64.tar.gz"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install "pen"
  end

  def caveats
    <<~TEXT
      Pen needs Docker with Compose v2 (on macOS, OrbStack, Colima or Docker Desktop).
      If you installed Pen from source before, remove ~/.local/bin/pen or put
      Homebrew earlier on your PATH.
    TEXT
  end

  test do
    assert_match "pen #{version}", shell_output("#{bin}/pen --version")
  end
end
EOF
